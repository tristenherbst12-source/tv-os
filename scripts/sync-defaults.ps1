# Copies config/*.json into launcher/js/defaults.js, the launcher's last-resort fallback
# (used only when neither the helper nor a cached copy is available).
# Run after editing anything in config/. Safe to run any time.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$out  = Join-Path $root 'launcher\js\defaults.js'

$parts = foreach ($name in 'apps', 'keymap', 'settings') {
    $json = Get-Content -Raw -Encoding UTF8 (Join-Path $root "config\$name.json")
    $null = $json | ConvertFrom-Json   # fail loudly on invalid JSON
    "  `"$name`": $($json.Trim())"
}

$text = "/* GENERATED by scripts/sync-defaults.ps1 from config/*.json. Do not edit by hand. */`n" +
        "window.TV_DEFAULTS = {`n" + ($parts -join ",`n") + "`n};`n"
[IO.File]::WriteAllText($out, $text, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $out"
